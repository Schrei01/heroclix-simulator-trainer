import '../../domain/board/cell_coordinate.dart';
import '../../domain/rules/line_of_sight.dart';
import '../../domain/training/exercise.dart';
import '../scenarios/scenario_document.dart';

Exercise personalExercise({
  required String id,
  required String title,
  required String instruction,
  required ScenarioDocument scenario,
  required SkillCategory category,
  required Difficulty difficulty,
  required QuestionType type,
  required ExerciseMetric metric,
  required String explanation,
  String sourceId = '',
  String targetId = '',
  CellCoordinate? origin,
  CellCoordinate? destination,
  Iterable<ExerciseOption> options = const [],
  Iterable<String> expected = const [],
  Iterable<CellCoordinate> solutionRoute = const [],
  Iterable<String> hints = const [],
  String manualGuide = '',
}) => Exercise(
  id: id,
  title: title.trim(),
  instruction: instruction.trim(),
  category: category,
  difficulty: difficulty,
  type: type,
  metric: metric,
  explanation: explanation.trim(),
  personal: true,
  rules: RuleSetVersion(scenario.rulesVersion),
  createdAt: DateTime.now().toUtc(),
  snapshotId: scenario.id,
  sourceId: sourceId,
  targetId: targetId,
  origin: origin,
  destination: destination,
  options: options,
  expected: expected,
  solutionRoute: solutionRoute,
  hints: hints,
  manualGuide: manualGuide.trim(),
  references: switch (metric) {
    ExerciseMetric.vision => ['11.4', '16'],
    ExerciseMetric.distance => ['11.3a'],
    ExerciseMetric.range => ['11.3b', '11.5'],
    ExerciseMetric.movement => ['10', '13.2', '16'],
    _ => const [],
  },
  teams: scenario.session.teams,
  world: VisionSnapshot(
    dimensions: scenario.session.dimensions,
    characters: scenario.session.characters.all,
    terrain: scenario.session.terrain,
    walls: scenario.session.walls,
  ),
);
